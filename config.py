# ★ 최고 속도와 실제 이동 속도는 다릅니다 ★
#
# 오래 이걸 하나로 뭉뚱그려 쓰다가, avoid_test 에서 "예상 2.32 m, 실측 1.73 m"
# 로 25% 가 빈 것을 보고 알았습니다. 로봇의 걸음은 한 발짝마다 빨라졌다
# 느려졌다 합니다. 순간 최고값만 보면 실제로 가는 거리를 크게 넘깁니다.
#
#   실측 (스틱 0.22, 같은 복도, 서로 다른 4번의 주행)
#       순간 최고    0.33 m/s
#       실제 평균    0.23 m/s      ← 최고값의 약 64%
#
#       2.6초 → 0.46 m    4.0초 → 0.82 m
#       4.1초 → 0.83 m    8.0초 → 1.73 m
#       전부  0.23 × (시간 − 0.5) 로 ±0.02 m 안에 들어맞습니다.
#
# 그래서 둘로 나눕니다.
#   STICK_TO_MPS       실제로 가는 속도 — **거리를 계산할 때** 씁니다
#   STICK_TO_MPS_PEAK  순간 최고 속도  — **안전 여유를 잡을 때** 씁니다
#
# 방향을 헷갈리면 안 됩니다.
#   "이 코스가 공간에 들어가는가" → 크게 잡아야 안전 → PEAK
#   "몇 미터쯤 가는가"            → 작게 잡아야 정확 → 평균
