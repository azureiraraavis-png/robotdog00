# 순서가 중요합니다. 긴 것부터 바꿔야 짧은 것이 안쪽을 깨뜨리지 않습니다.
# (예: "AI" 를 먼저 바꾸면 "AI응용소프트웨어과" 규칙이 영영 안 걸립니다)
TTS_FIXES = [
    ("AI응용소프트웨어과", "에이아이 응용 소프트웨어과"),
    ("AI 모델링", "에이아이 모델링"),
    ("AI", "에이아이"),
    ("301호", "삼백일 호"),
    ("302호", "삼백이 호"),
    ("303호", "삼백삼 호"),
]


def for_tts(text):
    """TTS 에 넣기 좋게 발음을 고칩니다."""
    for a, b in TTS_FIXES:
        text = text.replace(a, b)
    return text


