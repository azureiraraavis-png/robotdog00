# -*- coding: utf-8 -*-
"""
AI응용소프트웨어과 외빈 안내 — 304호에 **안 들어가는** 코스.

  기본 코스(ai_swe)에서 M4(문 통과)와 M5(방 안으로) 둘만 뺐습니다.
  문장은 한 글자도 안 바꿨습니다.

  ★ 이 파일에는 대본이 없습니다 ★

    대본은 `courses/ai_swe01/course.json` 에 있습니다. 이 파일은 그걸
    읽어서 등록만 합니다. **JSON 을 원본으로 쓰는 첫 코스입니다.**

    왜 그러냐면, 실행기가 아직 `.py` 만 찾기 때문입니다
    (`courses.discover` 가 `course_*.py` 를 훑습니다). 그래서 다리를
    하나 놓았습니다 — 등록은 파이썬이 하고, 내용은 JSON 이 갖습니다.

    코스를 고칠 때는 **JSON 을 고치세요.** 이 파일은 안 건드립니다.

  ── 무엇이 달라졌나 ──

    지점    S1 M1 S2 M2 S3 M3 S4 [M4 M5] S5
      →     S1 M1 S2 M2 S3 M3 S4         S5

    S4 에서 304호를 소개하고, **그 자리에서** 마무리합니다.

  ★ 눈에 안 보이는 변화가 하나 있었습니다 ★

    원본 S4 는 `face_back = False` 였습니다 — "이 문으로 들어갈
    것이므로 문을 본 채로 둡니다 (S4 → M4)". 그 문으로 안 들어가게
    됐으니 전제가 사라졌습니다.

    그대로 뒀다면 로봇은 문을 −72도로 본 채 굳고, 방문객에게 **등을
    돌린 채로** 마무리 인사 넷과 엎드리기를 했을 것입니다. 화면에는
    아무 문제도 안 뜹니다 — 복도에서 눈으로 봐야 압니다.

    그리고 방문객 쪽으로 돌아서는 일은 원래 M5 의 180도 회전이 하고
    있었습니다. M5 를 빼면 그것도 같이 사라집니다. 지금은 S4 의
    `face_back = True` 가 복도 쪽으로 되돌리는 일을 대신합니다.

  ★ 아직 사람이 봐야 하는 것 ★

    마지막 `s5e_rest` 는 로봇이 **엎드리는** 동작입니다. 원본에서는
    방 안이었는데 이제 복도입니다. 통행에 걸리면 JSON 에서 그 줄을
    빼세요. 엎드리기는 "안내가 끝났다" 는 가장 분명한 신호라 값이
    있지만, 자리를 봐야 합니다.

  ── 확인 (로봇 없이 됩니다) ──

        .\\run courses.py                        찾았는지, 이름이 안 겹치는지
        .\\run guide.py --dry --course ai_swe01   순서와 시간표
        .\\run studio.py plan ai_swe01            무엇을 만들고 올려야 하는지
"""

from pathlib import Path

import coursefile

CID = "ai_swe01"

# ★ 못 읽으면 조용히 넘어가지 않습니다 ★
#   courses.discover 가 예외를 잡아 PROBLEMS 에 적고, 그것이
#   guide.py 시작할 때 화면에 뜹니다. 코스가 메뉴에 안 뜨는데
#   아무도 이유를 말해주지 않는 것이 제일 나쁩니다.
_path = coursefile.path_of(CID, "course.json")
if not _path.exists():
    raise FileNotFoundError(
        f"{_path} 가 없습니다.\n"
        f"      이 코스의 대본은 그 JSON 파일에 있습니다. "
        f"이 파이썬 파일은 읽어서 등록만 합니다."
    )

COURSE = coursefile.load(CID)

# 읽어놓고 아닌 것을 등록하면 안 됩니다 — 파일 이름과 안의 id 가
# 어긋나는 일은 복사해 만들 때 실제로 일어납니다.
assert COURSE.id == CID, f"JSON 안의 id 가 '{COURSE.id}' 입니다 ('{CID}' 여야 합니다)"
